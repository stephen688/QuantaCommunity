    // 校验并清理昵称
    private String sanitizeLoginNickName(String nickName) {
        if (nickName == null || nickName.trim().isEmpty()) {
            return null;
        }
        nickName = nickName.trim();
        if (nickName.length() > 20) {
            throw new LoginFailedException("昵称不能超过 20 个字符");
        }
        return sensitiveWordChecker.replaceSensitiveWords(nickName);
    }


    // 校验并清理头像 URL
    private String sanitizeLoginAvatarUrl(String avatarUrl) {
        if (avatarUrl == null || avatarUrl.trim().isEmpty()) {
            return null;
        }
        avatarUrl = avatarUrl.trim();
        if (!avatarUrl.startsWith("http://") && !avatarUrl.startsWith("https://")) {
            throw new LoginFailedException("头像 URL 格式不正确");
        }
        return avatarUrl;
    }

    private boolean isAutoGeneratedNickName(String nickName) {
        return nickName == null || nickName.isEmpty() || nickName.startsWith(USER_NICK_NAME_PREFIX);
    }

    /** 联调 mock 账号的默认昵称，允许登录时用用户填写的昵称覆盖 */
    private boolean isPlaceholderNickName(String nickName) {
        return isAutoGeneratedNickName(nickName)
                || "测试用户".equals(nickName)
                || "测试用户B".equals(nickName);
    }

    /**
     * 登录时同步微信授权的昵称/头像到数据库
     * 业务规则：
     * - 新用户：直接写入微信授权的昵称和头像
     * - 老用户：仅在昵称为默认昵称（未自定义）或头像为空时，才用授权信息补全，避免覆盖用户已自定义的资料
     * 执行步骤：
     * 1. 清理并校验昵称和头像URL（过滤敏感词、非法字符）
     * 2. 若两者均为空则直接返回，无需更新
     * 3. 构建更新对象，根据 isNewUser 标志执行不同策略：
     *    - 新用户：直接设置昵称和头像
     *    - 老用户：判断是否为默认昵称或头像为空，满足条件才更新
     * 4. 若有字段发生变更，执行数据库更新
     * 
     * @param user 当前用户对象（用于判断是否为默认昵称/头像为空）
     * @param userLoginDTO 微信登录请求DTO（包含授权后的昵称和头像）
     * @param isNewUser 是否为新注册用户
     */
    private void syncWeChatProfileOnLogin(User user, UserLoginDTO userLoginDTO, boolean isNewUser) {
        String nickName = sanitizeLoginNickName(userLoginDTO.getNickName());
        String avatarUrl = sanitizeLoginAvatarUrl(userLoginDTO.getAvatarUrl());
        if (nickName == null && avatarUrl == null) {
            return;
        }

        // 构建更新对象
        User update = User.builder().id(user.getId()).updateTime(LocalDateTime.now()).build();
        boolean changed = false;


        // 新用户直接写入昵称和头像
        if (isNewUser) {
            if (nickName != null) {
                user.setNickName(nickName);
                update.setNickName(nickName);
                changed = true;
            }
            if (avatarUrl != null) {
                user.setAvatarUrl(avatarUrl);
                update.setAvatarUrl(avatarUrl);
                changed = true;
            }
            // 老用户仅在资料未完善时用授权信息补全
        } else {
            if (nickName != null && isPlaceholderNickName(user.getNickName())) {
                user.setNickName(nickName);
                update.setNickName(nickName);
                changed = true;
            }
            if (avatarUrl != null && (user.getAvatarUrl() == null || user.getAvatarUrl().trim().isEmpty())) {
                user.setAvatarUrl(avatarUrl);
                update.setAvatarUrl(avatarUrl);
                changed = true;
            }
        }

        if (changed) {
            userMapper.updateById(update);
        }
    }

    /**
     * 微信登录
     * 1.调用微信接口服务，用 code 换取 openid
     * 2.新用户入库；若请求携带授权后的 nickName/avatarUrl 则一并写入
     * 3.老用户仅在资料未完善时用授权信息补全
     */
    @Override
    public User weChatLogin(UserLoginDTO userLoginDTO) {

       //参数校验
        String code = userLoginDTO == null ? null : userLoginDTO.getCode();
        if (code == null || code.trim().isEmpty()) {
            throw new LoginFailedException("微信登录凭证不能为空");
        }
        code = code.trim();
        // 测试模式：当code为"test"时，直接生成测试用户
        if ("test".equals(code)) {
            User user = userMapper.getByOpenid("test_openid_123456");
            boolean isNewUser = user == null;
            if (isNewUser) {
                user = getOrCreateTestUser("test_openid_123456", "测试用户");
            }
            syncWeChatProfileOnLogin(user, userLoginDTO, isNewUser);
            return user;
        }
        if ("test2".equals(code)) {
            User user = userMapper.getByOpenid("test_openid_2");
            boolean isNewUser = user == null;
            if (isNewUser) {
                user = getOrCreateTestUser("test_openid_2", "测试用户B");
            }
            syncWeChatProfileOnLogin(user, userLoginDTO, isNewUser);
            return user;
        }
        // 1. 调用微信接口服务，获取当前微信用户信息
        Map<String, String> map = new HashMap<>();
        map.put("appid", weChatProperties.getAppid());
        map.put("secret", weChatProperties.getSecret());
        map.put("js_code", userLoginDTO.getCode());
        map.put("grant_type", "authorization_code");
//        // 打印请求参数（用于调试）
//        System.out.println("=== 微信登录请求参数 ===");
//        System.out.println("appid: " + weChatProperties.getAppid());
//        System.out.println("secret: " + weChatProperties.getSecret());
//        System.out.println("code: " + userLoginDTO.getCode());
        String json = HttpClientUtil.doGet(WX_LOGIN, map);
//        // 打印微信返回结果
//        System.out.println("=== 微信返回结果 ===");
//        System.out.println(json);
       //2.解析JSON字符串
        JSONObject jsonObject;
        try {
            jsonObject = JSONObject.parseObject(json);
        } catch (Exception e) {
            log.error("微信登录返回非JSON，body={}", json);
            throw new LoginFailedException("微信登录失败：响应格式异常");
        }
        String openid = jsonObject.getString("openid");
        // 检查是否有错误码
        Integer errcode = jsonObject.getInteger("errcode");
        String errmsg = jsonObject.getString("errmsg");
        if (errcode != null) {
            log.error("微信登录失败，errcode={}, errmsg={}", errcode, errmsg);
            throw new LoginFailedException("微信登录失败：" + errmsg);
        }
        //判断是否为空
        if (openid == null) {
            log.error("微信登录失败，openid为空，完整返回：{}", json);
            throw new LoginFailedException("微信登录失败");
        }
        //3.判断当前用户是否为新用户，如果是就创建新用户
        User user = userMapper.getByOpenid(openid);
        boolean isNewUser = user == null;
        String weChatNickName = sanitizeLoginNickName(userLoginDTO.getNickName());
        String weChatAvatarUrl = sanitizeLoginAvatarUrl(userLoginDTO.getAvatarUrl());

        if (isNewUser) {
            String nickName = weChatNickName != null
                    ? weChatNickName
                    : USER_NICK_NAME_PREFIX + RandomUtil.randomString(8);
            user = User.builder()
                    .openid(openid)
                    .nickName(nickName)
                    .avatarUrl(weChatAvatarUrl)
                    .createTime(LocalDateTime.now())
                    .updateTime(LocalDateTime.now())
                    .build();
            userMapper.insert(user);
        } else {
            syncWeChatProfileOnLogin(user, userLoginDTO, false);
        }
        //4.返回用户信息
        return user;
    }


    /**
     * 用户认证身份
     * 1.参数校验：认证信息不能为空，认证类型、真实姓名、学校ID不能为空
     * 2.获取当前用户认证信息
     * 3.首次认证，直接新增
     * 4.如果用户被驳回，可重新认证，更新认证信息，重置审核状态为待审核，清空审核备注和审核时间
     * 5.待审核，已通过，禁止重新认证
     */
    @Override
    public UserAuth addUserAuth(UserAuthDTO userAuthDTO) {

        //1.参数校验
        if (userAuthDTO == null) {
            throw new AuthFailedException("认证参数不能为空");
        }
        if (userAuthDTO.getIdentityType() == null ||
                userAuthDTO.getRealName() == null || userAuthDTO.getRealName().trim().isEmpty() ||
                userAuthDTO.getSchoolId() == null || userAuthDTO.getSchoolId().trim().isEmpty() ||
                userAuthDTO.getQuantaBatch() == null || userAuthDTO.getQuantaBatch().trim().isEmpty() ||
                userAuthDTO.getQuantaDepartment() == null || userAuthDTO.getQuantaDepartment().trim().isEmpty()) {
            throw new AuthFailedException("认证信息不完整");
        }
        //2.获取当前用户认证信息
        Long userId = BaseContext.getCurrentId();
        UserAuth userAuth = userMapper.getUserAuthByUserId(userId);
        //3.首次认证，直接新增
        if (userAuth == null) {
            //1.复制到实体类
            userAuth = BeanUtil.copyProperties(userAuthDTO, UserAuth.class);
            //2.补全字段
            userAuth.setUserId(userId);
            userAuth.setAuditStatus(AuditStatus.PENDING.getCode());
            userAuth.setCreateTime(LocalDateTime.now());
            userAuth.setUpdateTime(LocalDateTime.now());
            userMapper.insertUserAuth(userAuth);
            syncUserAuthDisplayStatus(userId, UserAuthDisplayStatus.PENDING);
            return userAuth;
        }
        //3.如果用户被驳回，可重新认证
        if (Objects.equals(userAuth.getAuditStatus(), AuditStatus.REJECTED.getCode())) {
            // 允许更新认证信息
            userAuth.setIdentityType(userAuthDTO.getIdentityType());
            userAuth.setRealName(userAuthDTO.getRealName());
            userAuth.setSchoolId(userAuthDTO.getSchoolId());
            userAuth.setQuantaBatch(userAuthDTO.getQuantaBatch());
            userAuth.setQuantaDepartment(userAuthDTO.getQuantaDepartment());
            userAuth.setAuditStatus(AuditStatus.PENDING.getCode());  // 重置为待审核
            userAuth.setAuditRemark(null);
            userAuth.setAuditTime(null);
            userAuth.setUpdateTime(LocalDateTime.now());
            userMapper.updateUserAuth(userAuth);
            syncUserAuthDisplayStatus(userId, UserAuthDisplayStatus.PENDING);
            return userAuth;
        }
        //待审核，已通过，禁止重新认证
        if (Objects.equals(userAuth.getAuditStatus(), AuditStatus.APPROVED.getCode())) {
            throw new AuthFailedException("用户已经认证过了");
        }
       if (Objects.equals(userAuth.getAuditStatus(), AuditStatus.PENDING.getCode())) {
            throw new AuthFailedException("用户正在审核中，不能重新认证");
        }
       throw new AuthFailedException("当前状态不能重新认证");
    }


