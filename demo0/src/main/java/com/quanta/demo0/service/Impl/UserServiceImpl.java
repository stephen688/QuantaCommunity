    /**
     * 更新用户信息(昵称、头像)
     * 昵称有敏感词需要过滤掉，替换成***
     * 昵称长度限制在1-20个字符
     * 头像URL必须以http://或https://开头
     */
    @Override
    public void updateUserInfo(UserInfoDTO userInfoDTO) {
        // 1. 校验昵称和头像不能同时为空
        if ((userInfoDTO.getNickName() == null || userInfoDTO.getNickName().trim().isEmpty()) &&
                (userInfoDTO.getAvatarUrl() == null || userInfoDTO.getAvatarUrl().trim().isEmpty())) {
            throw new UserInfoFailedException("昵称和头像不能同时为空");
        }
        // 2. 校验昵称长度（1-20 个字符）
        if (userInfoDTO.getNickName() != null && !userInfoDTO.getNickName().trim().isEmpty()) {
            String nickName = userInfoDTO.getNickName().trim();
            if (nickName.length() > 20) {
                throw new UserInfoFailedException("昵称不能超过 20 个字符");
            }
        }

        //3.校验敏感词（有的话替换成***）
        String nickName = userInfoDTO.getNickName();
        if (nickName != null && !nickName.trim().isEmpty()) {
            nickName = sensitiveWordChecker.replaceSensitiveWords(nickName);
            userInfoDTO.setNickName(nickName);
        }


        //3.校验Url
        if (userInfoDTO.getAvatarUrl() != null && !userInfoDTO.getAvatarUrl().trim().isEmpty()) {
            String avatarUrl = userInfoDTO.getAvatarUrl().trim();
            // 校验 URL 格式：必须以 http:// 或 https:// 开头
            if (!avatarUrl.startsWith("http://") && !avatarUrl.startsWith("https://")) {
                throw new UserInfoFailedException("头像 URL 格式不正确");
            }
        }
        //-----业务逻辑------


        //1.更新1用户信息
        User user = BeanUtil.copyProperties(userInfoDTO, User.class);
        user.setId(BaseContext.getCurrentId());
        user.setUpdateTime(LocalDateTime.now());
      //2.更新数据库
       int rows =  userMapper.updateById(user);
       if(rows == 0){
           throw new UserInfoFailedException("更新用户信息失败");
       }
    }


    /**
     * 获取用户认证状态
     * 1.根据用户ID查询认证信息
     * 2.用户没有认证过，返回-1，告诉前端用户没有认证过
     * 3.用户认证失败,返回认证备注
     * 4.用户认证中，返回1
     * 5.用户认证通过，返回2
     */
    @Override
    public UserAuthStatusVO getAuthStatus(Long currentId) {
        UserAuth userAuth = userMapper.getUserAuthByUserId(currentId);
        if (userAuth == null) {
            //说明用户没有认证过，返回-1,告诉前端用户没有认证过
            return UserAuthStatusVO.builder()
                    .auditStatus(AuditStatus.UNSUBMITTED.getCode())
                    .build();
        }

        if (Objects.equals(userAuth.getAuditStatus(), AuditStatus.REJECTED.getCode())) {
            //说明用户认证失败,返回认证备注
            return UserAuthStatusVO.builder()
                    .auditStatus(userAuth.getAuditStatus())
                    .auditRemark(userAuth.getAuditRemark())
                    .build();
        }
      return UserAuthStatusVO.builder()
                .auditStatus(userAuth.getAuditStatus())
                .build();
    }



